create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  body text not null,
  created_at timestamptz not null default now(),
  user_id uuid references auth.users (id)
);

alter table public.posts
  drop constraint if exists posts_body_length_check;
alter table public.posts
  add constraint posts_body_length_check
  check (char_length(btrim(body)) between 1 and 280);

alter table public.posts
  alter column user_id drop not null;

alter table public.posts enable row level security;

drop policy if exists "wall_posts_read" on public.posts;
create policy "wall_posts_read"
  on public.posts
  for select
  to anon, authenticated
  using (true);

drop policy if exists "wall_posts_insert" on public.posts;
create policy "wall_posts_insert"
  on public.posts
  for insert
  to anon, authenticated
  with check (
    char_length(btrim(body)) between 1 and 280
    and (user_id is null or user_id = auth.uid())
  );

grant select, insert on table public.posts to anon, authenticated;

do $$
begin
  if not exists (
    select 1
    from pg_publication_tables
    where pubname = 'supabase_realtime'
      and schemaname = 'public'
      and tablename = 'posts'
  ) then
    alter publication supabase_realtime add table public.posts;
  end if;
end
$$;
